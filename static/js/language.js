function updateMediFlowProfileUI() {
    let profile = null;
    try { profile = JSON.parse(localStorage.getItem("mediflow_profile") || "null"); } catch (_) {}
    const name = (profile && profile.name) || localStorage.getItem("mediflow_userName") || "MediFlow User";
    document.querySelectorAll("#globalUserName").forEach(el => {
        el.textContent = name;
        el.removeAttribute("data-i18n");
    });
    document.querySelectorAll("#globalUserAvatar").forEach(el => {
        const initials = name === "MediFlow User" ? "MF" : name.split(/\s+/).filter(Boolean).map(x => x[0]).join("").slice(0,2).toUpperCase();
        el.textContent = initials || "MF";
    });
}

