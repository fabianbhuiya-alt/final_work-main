function mediflowSymptomLabel(symptom) {
    const key = String(symptom || '').trim().toLowerCase();
    if (getCurrentLanguage && getCurrentLanguage() === 'Bangla') {
        return MEDIFLOW_SYMPTOM_BANGLA[key] || translateText(symptom);
    }
    return symptom;
}

function mediflowResolveSymptomInput(input, symptoms) {
    const value = String(input || '').trim();
    const lower = value.toLowerCase();
    const list = Array.isArray(symptoms) ? symptoms : [];
    const exact = list.find(s => String(s).toLowerCase() === lower);
    if (exact) return exact;
    if (getCurrentLanguage() === 'Bangla') {
        const translated = list.find(s => mediflowSymptomLabel(s).toLowerCase() === lower);
        if (translated) return translated;
    }
    return null;
}


/* =========================================================
   GLOBAL LANGUAGE ENGINE
   ========================================================= */

const MEDIFLOW_LANGUAGE_KEY = "mediflow_language";
const MEDIFLOW_LANGUAGE_FALLBACK_KEY = "language";
const MEDIFLOW_DEFAULT_LANGUAGE = "English";

function normalizeLanguage(value) {
    return value === "Bangla" ? "Bangla" : "English";
}

function getCurrentLanguage() {
    const stored =
        localStorage.getItem(MEDIFLOW_LANGUAGE_KEY) ||
        localStorage.getItem(MEDIFLOW_LANGUAGE_FALLBACK_KEY) ||
        MEDIFLOW_DEFAULT_LANGUAGE;

    return normalizeLanguage(stored);
}

function setCurrentLanguage(language) {
    const normalized = normalizeLanguage(language);
    localStorage.setItem(MEDIFLOW_LANGUAGE_KEY, normalized);
    localStorage.setItem(MEDIFLOW_LANGUAGE_FALLBACK_KEY, normalized);
    return normalized;
}

function getCurrentTheme() {
    return localStorage.getItem("mediflow_theme") || "light";
}

function applyTheme(theme) {
    const normalized = theme === "dark" ? "dark" : "light";
    if (document.body) {
        document.body.classList.toggle("dark", normalized === "dark");
        document.body.dataset.theme = normalized;
    }
    localStorage.setItem("mediflow_theme", normalized);
    return normalized;
}

function getSpeechLanguage() {
    return getCurrentLanguage() === "Bangla" ? "bn-BD" : "en-US";
}

function translateText(text) {
    if (!text || !text.trim()) return text;

    const language = getCurrentLanguage();
    if (!translations[language]) return text;

    const cleanText = text.trim();
    const exact = translations[language][cleanText];
    if (exact) {
        const start = text.indexOf(cleanText);
        return text.slice(0, start) + exact + text.slice(start + cleanText.length);
    }

    // Translate known phrases inside dynamically generated text as well.
    let result = text;
    const entries = Object.entries(translations[language])
        .filter(([k, v]) => language === 'Bangla' && k && v && k !== v && k.length >= 3)
        .sort((a, b) => b[0].length - a[0].length);
    for (const [from, to] of entries) {
        if (result.includes(from)) result = result.split(from).join(to);
    }
    return result;
}

const mediflowOriginalText = new WeakMap();

function translateNormalTextNodes(language) {
    const walker = document.createTreeWalker(
        document.body,
        NodeFilter.SHOW_TEXT
    );
    const nodes = [];

    while (walker.nextNode()) nodes.push(walker.currentNode);

    nodes.forEach(node => {
        const parent = node.parentElement;
        if (!parent || parent.closest("script, style, textarea, input, select, option")) return;

        if (!mediflowOriginalText.has(node)) {
            mediflowOriginalText.set(node, node.nodeValue);
        }

        const original = mediflowOriginalText.get(node);

        const nextValue = language === "Bangla"
            ? translateText(original)
            : original;

        // Avoid writing the same text back into the DOM.
        // Re-writing text nodes causes unnecessary mutation events.
        if (node.nodeValue !== nextValue) {
            node.nodeValue = nextValue;
        }
    });
}

function applyLanguage() {
    const language = getCurrentLanguage();
    applyTheme(getCurrentTheme());

    document.documentElement.lang = language === "Bangla" ? "bn" : "en";
    document.documentElement.dataset.language = language;

    document.querySelectorAll("[data-i18n]").forEach(element => {
        const key = element.getAttribute("data-i18n");
        if (translations[language] && translations[language][key]) {
            const translated = translations[language][key];
            if (element.textContent !== translated) {
                element.textContent = translated;
            }
        }
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach(element => {
        const key = element.getAttribute("data-i18n-placeholder");
        if (translations[language] && translations[language][key]) {
            element.placeholder = translations[language][key];
        }
    });

    document.querySelectorAll("[data-i18n-title]").forEach(element => {
        const key = element.getAttribute("data-i18n-title");
        if (translations[language] && translations[language][key]) {
            element.title = translations[language][key];
        }
    });

    document.querySelectorAll("[title]").forEach(element => {
        if (element.hasAttribute("data-i18n-title")) return;
        const original = element.getAttribute("data-original-title") || element.title;
        if (!element.hasAttribute("data-original-title")) {
            element.setAttribute("data-original-title", original);
        }
        element.title = language === "Bangla" ? translateText(original) : original;
    });

    translateNormalTextNodes(language);

    // Translate native select options without changing their internal values.
    document.querySelectorAll("option").forEach(option => {
        if (option.hasAttribute("data-i18n")) return;
        const original = option.getAttribute("data-original-text") || option.textContent.trim();
        if (!option.hasAttribute("data-original-text")) option.setAttribute("data-original-text", original);
        option.textContent = language === "Bangla" ? translateText(original) : original;
    });

    // Translate common accessibility/user-facing attributes.
    document.querySelectorAll("[aria-label]").forEach(element => {
        const original = element.getAttribute("data-original-aria-label") || element.getAttribute("aria-label");
        if (!element.hasAttribute("data-original-aria-label")) element.setAttribute("data-original-aria-label", original);
        element.setAttribute("aria-label", language === "Bangla" ? translateText(original) : original);
    });
    document.querySelectorAll("[alt]").forEach(element => {
        const original = element.getAttribute("data-original-alt") || element.getAttribute("alt");
        if (!element.hasAttribute("data-original-alt")) element.setAttribute("data-original-alt", original);
        element.setAttribute("alt", language === "Bangla" ? translateText(original) : original);
    });

    const pageTitle = document.title || "MediFlow";
    if (!document.documentElement.hasAttribute("data-original-title")) {
        document.documentElement.setAttribute("data-original-title", pageTitle);
    }
    const originalPageTitle = document.documentElement.getAttribute("data-original-title");
    document.title = language === "Bangla" ? translateText(originalPageTitle) : originalPageTitle;

    document.querySelectorAll("#languageSelect").forEach(select => {
        select.value = language;
    });

    window.dispatchEvent(new CustomEvent("mediflow:languageChanged", {
        detail: { language, speechLanguage: getSpeechLanguage() }
    }));
}

function setupLanguageObserver() {
    if (typeof MutationObserver === "undefined" || !document.body) return;

    let scheduled = false;
    let observer;

    const scheduleApply = () => {
        if (scheduled) return;
        scheduled = true;
        setTimeout(() => {
            scheduled = false;
            observer.disconnect();
            try {
                applyLanguage();
            } finally {
                observer.observe(document.body, { childList: true, subtree: true });
            }
        }, 0);
    };

    observer = new MutationObserver((mutations) => {
        // Only react to newly inserted DOM. Attribute changes and text-node
        // changes made by translation itself must not trigger another scan.
        const relevant = mutations.some(m => m.type === "childList" && m.addedNodes.length);
        if (relevant) scheduleApply();
    });

    observer.observe(document.body, { childList: true, subtree: true });
}



